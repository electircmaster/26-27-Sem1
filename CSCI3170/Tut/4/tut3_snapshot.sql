WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
WHENEVER OSERROR EXIT FAILURE ROLLBACK
SET ECHO OFF
SET VERIFY OFF
SET FEEDBACK OFF
SET HEADING OFF
SET PAGESIZE 0
SET LINESIZE 300
SET TRIMSPOOL ON
SET TAB OFF
SET TERMOUT OFF
SPOOL &1 REPLACE
SELECT 'COLUMN|' || TABLE_NAME || '|' || TO_CHAR(COLUMN_ID, 'FM9990') || '|' || COLUMN_NAME || '|' || DATA_TYPE || '|' || TO_CHAR(DATA_LENGTH, 'FM9990') || '|' || NULLABLE
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME IN ('OFFICE','ENGINEER','PROJECT','APPLICATION','MAINTAIN','RESEARCH')
ORDER BY TABLE_NAME, COLUMN_ID;
SELECT 'KEY|' || c.TABLE_NAME || '|' || c.CONSTRAINT_TYPE || '|' || k.COLUMN_NAME || '|' || NVL(r.TABLE_NAME, '-') || '|' || NVL(r.COLUMN_NAME, '-')
FROM USER_CONSTRAINTS c
JOIN USER_CONS_COLUMNS k ON c.CONSTRAINT_NAME = k.CONSTRAINT_NAME
LEFT
JOIN USER_CONS_COLUMNS r ON c.R_CONSTRAINT_NAME = r.CONSTRAINT_NAME AND k.POSITION = r.POSITION
WHERE c.TABLE_NAME IN ('OFFICE','ENGINEER','PROJECT','APPLICATION','MAINTAIN','RESEARCH') AND c.CONSTRAINT_TYPE IN ('P','R')
ORDER BY c.TABLE_NAME, c.CONSTRAINT_TYPE, k.COLUMN_NAME;
SELECT 'DATA|OFFICE|' || TO_CHAR(OFFICEID, 'FM999999999990') || '|' || ONAME || '|' || OADDRESS || '|' || OPHONENUM
FROM OFFICE
ORDER BY OFFICEID;
SELECT 'COUNT|OFFICE|' || TO_CHAR(COUNT(*), 'FM999999990')
FROM OFFICE;
SELECT 'DATA|ENGINEER|' || TO_CHAR(ENGINEERID, 'FM999999999990') || '|' || ENAME || '|' || TO_CHAR(ESALARY, 'FM999999999990') || '|' || TO_CHAR(OFFICEID, 'FM999999999990')
FROM ENGINEER
ORDER BY ENGINEERID;
SELECT 'COUNT|ENGINEER|' || TO_CHAR(COUNT(*), 'FM999999990')
FROM ENGINEER;
SELECT 'DATA|PROJECT|' || TO_CHAR(PROJECTID, 'FM999999999990') || '|' || TO_CHAR(OFFICEID, 'FM999999999990') || '|' || PNAME || '|' || PCATEGORY || '|' || TO_CHAR(PBUDGET, 'FM999999999990') || '|' || TO_CHAR(PEXPENDITURE, 'FM999999999990')
FROM PROJECT
ORDER BY PROJECTID;
SELECT 'COUNT|PROJECT|' || TO_CHAR(COUNT(*), 'FM999999990')
FROM PROJECT;
SELECT 'DATA|APPLICATION|' || TO_CHAR(APPID, 'FM999999999990') || '|' || ANAME || '|' || TO_CHAR(APRICE, 'FM999999999990') || '|' || TO_CHAR(ADATE, 'FM999999999990') || '|' || TO_CHAR(PROJECTID, 'FM999999999990')
FROM APPLICATION
ORDER BY APPID;
SELECT 'COUNT|APPLICATION|' || TO_CHAR(COUNT(*), 'FM999999990')
FROM APPLICATION;
SELECT 'DATA|MAINTAIN|' || TO_CHAR(APPID, 'FM999999999990') || '|' || TO_CHAR(ENGINEERID, 'FM999999999990')
FROM MAINTAIN
ORDER BY APPID, ENGINEERID;
SELECT 'COUNT|MAINTAIN|' || TO_CHAR(COUNT(*), 'FM999999990')
FROM MAINTAIN;
SELECT 'DATA|RESEARCH|' || TO_CHAR(PROJECTID, 'FM999999999990') || '|' || TO_CHAR(ENGINEERID, 'FM999999999990')
FROM RESEARCH
ORDER BY PROJECTID, ENGINEERID;
SELECT 'COUNT|RESEARCH|' || TO_CHAR(COUNT(*), 'FM999999990')
FROM RESEARCH;
SPOOL OFF
SET TERMOUT ON
SET FEEDBACK ON
SET HEADING ON
SET PAGESIZE 50
PROMPT Snapshot saved.
