-- Drops ONLY the six lab tables. Save your comparison traces first.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET SERVEROUTPUT ON
ROLLBACK;
BEGIN
  FOR t IN (
    SELECT 'RESEARCH' name, 1 seq FROM DUAL UNION ALL
    SELECT 'MAINTAIN', 2 FROM DUAL UNION ALL
    SELECT 'APPLICATION', 3 FROM DUAL UNION ALL
    SELECT 'PROJECT', 4 FROM DUAL UNION ALL
    SELECT 'ENGINEER', 5 FROM DUAL UNION ALL
    SELECT 'OFFICE', 6 FROM DUAL
    ORDER BY 2
  ) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE ' || t.name;
      DBMS_OUTPUT.PUT_LINE('Dropped ' || t.name);
    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE = -942 THEN
          DBMS_OUTPUT.PUT_LINE(t.name || ' was already absent');
        ELSE
          RAISE;
        END IF;
    END;
  END LOOP;
END;
/
SELECT COUNT(*) AS LAB_TABLES_REMAINING FROM USER_TABLES
WHERE TABLE_NAME IN
 ('OFFICE','ENGINEER','PROJECT','APPLICATION','MAINTAIN','RESEARCH');
-- Expected: 0. DROP is DDL; these changes cannot be rolled back.
